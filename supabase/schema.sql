  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'chemfarm_players'
  ) then alter publication supabase_realtime add table public.chemfarm_players; end if;
end $$;
